# User defined functions
# A user-defined function is a block of code that performs a specific task, defined by the user.
# It is created using the def keyword followed by the function name and parentheses ().
# The function can take parameters (inputs) and can return a value using the return statement.
# Defining a user-defined function
def add_numbers(a, b):
    """This function adds two numbers and returns the result."""
    print(f"The sum is: {a + b}")
# Calling the user-defined function
add_numbers(5, 3)
# Output: The sum is: 8