# \n - new/next line
# \t - tab
# \\ - backslash
# \' - inserts a single quote inside a single-quoted string

#\n
print("Hello everyone. \nHow are you?")

# \t
print("John 20")
print("John\t20")

# \\
print("yes\\old")
print("yes\\no")

# \'
print('This is a Python\'s class')
print("This is a Python's class")